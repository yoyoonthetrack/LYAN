/**
 * Writes .env.staging-v2 from Staging V2 Management API keys.
 * Reads the PAT from .env.local only. Never copies production REST keys.
 * Stripe Test keys may be reused (sk_test_ / pk_test_ only).
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { STAGING_REF, PRODUCTION_REF, jwtRef } = require('./staging-v2-guard');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, '.env.staging-v2');

function parseEnvFile(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const line of fs.readFileSync(file, 'utf8').split(/\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue;
    const i = trimmed.indexOf('=');
    out[trimmed.slice(0, i)] = trimmed.slice(i + 1).replace(/^['"]|['"]$/g, '');
  }
  return out;
}

function quote(value) {
  return JSON.stringify(String(value));
}

(async () => {
  const local = parseEnvFile(path.join(ROOT, '.env.local'));
  const token = process.env.SUPABASE_ACCESS_TOKEN || local.SUPABASE_ACCESS_TOKEN;
  if (!token) {
    console.error('FAIL missing SUPABASE_ACCESS_TOKEN in environment or .env.local (Management PAT only)');
    process.exit(1);
  }

  const res = await fetch(`https://api.supabase.com/v1/projects/${STAGING_REF}/api-keys`, {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' },
  });
  const keys = await res.json();
  if (!Array.isArray(keys) || res.status !== 200) {
    console.error('FAIL Management API keys http=' + res.status);
    process.exit(1);
  }

  const anon = keys.find((k) => k.name === 'anon');
  const service = keys.find((k) => k.name === 'service_role');
  const anonKey = anon && (anon.api_key || anon.key);
  const serviceKey = service && (service.api_key || service.key);
  if (!anonKey || !serviceKey) {
    console.error('FAIL Staging V2 anon or service_role key missing from Management API');
    process.exit(1);
  }
  if (jwtRef(anonKey) !== STAGING_REF || jwtRef(serviceKey) !== STAGING_REF) {
    console.error('FAIL Staging keys JWT ref mismatch');
    process.exit(1);
  }
  if (jwtRef(anonKey) === PRODUCTION_REF || jwtRef(serviceKey) === PRODUCTION_REF) {
    console.error('FAIL refused production JWT');
    process.exit(1);
  }

  const stripeSecret = process.env.STRIPE_SECRET_KEY || local.STRIPE_SECRET_KEY || '';
  const stripePub = process.env.STRIPE_PUBLISHABLE_KEY || local.STRIPE_PUBLISHABLE_KEY || '';
  const stripeWh = process.env.STRIPE_WEBHOOK_SECRET || local.STRIPE_WEBHOOK_SECRET || '';
  if (stripeSecret.startsWith('sk_live') || stripePub.startsWith('pk_live')) {
    console.error('FAIL refused to copy Stripe Live into Staging env');
    process.exit(1);
  }
  if (stripeSecret && !stripeSecret.startsWith('sk_test_')) {
    console.error('FAIL Stripe secret is not sk_test_');
    process.exit(1);
  }

  const url = `https://${STAGING_REF}.supabase.co`;
  const lines = [
    '# LYANN Staging V2 — local isolation. Do not use on Vercel production.',
    `# Project: Lyann-staging-v2 (${STAGING_REF})`,
    '# Generated by scripts/write-staging-v2-env.js. Gitignored.',
    `SUPABASE_URL=${quote(url)}`,
    `LYANN_SUPABASE_URL=${quote(url)}`,
    `SUPABASE_ANON_KEY=${quote(anonKey)}`,
    `LYANN_SUPABASE_ANON_KEY=${quote(anonKey)}`,
    `SUPABASE_SERVICE_ROLE_KEY=${quote(serviceKey)}`,
    `LYANN_SUPABASE_SERVICE_ROLE_KEY=${quote(serviceKey)}`,
    `LYANN_E2E_WRITE_PROJECT_REF=${STAGING_REF}`,
    'LYANN_E2E_ALLOW_WRITES=1',
    'PORT=8098',
    'LYANN_E2E_BASE_URL=http://127.0.0.1:8098',
  ];
  if (stripeSecret) lines.push(`STRIPE_SECRET_KEY=${quote(stripeSecret)}`);
  if (stripePub) lines.push(`STRIPE_PUBLISHABLE_KEY=${quote(stripePub)}`);
  if (stripeWh) lines.push(`STRIPE_WEBHOOK_SECRET=${quote(stripeWh)}`);
  lines.push('');

  fs.writeFileSync(OUT, lines.join('\n'), { mode: 0o600 });
  console.log(JSON.stringify({
    wrote: '.env.staging-v2',
    target: STAGING_REF,
    url,
    anon_ref: jwtRef(anonKey),
    service_ref: jwtRef(serviceKey),
    stripe: stripeSecret ? 'sk_test' : 'absent',
    production_keys_copied: false,
    env_local_modified: false,
  }));
})().catch((err) => {
  console.error('FAIL', String(err && err.message || err).slice(0, 200));
  process.exit(1);
});
