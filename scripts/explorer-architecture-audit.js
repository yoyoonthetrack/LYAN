const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = file => fs.readFileSync(file, 'utf8');
const repo = read('explorer-repository.js');
const ui = read('explorer-ui.js');
const results = read('results.html');
const api = read('api-client.js');
assert(repo.includes("readAll('public_profiles')"), 'Discovery must use public identity, not private profiles');
assert(repo.includes("readAll('services', q => q.eq('is_active', true))"), 'Real active services required');
assert(repo.includes("readAll('requests', q => q.eq('visibility', 'PUBLIC').eq('status', 'OPEN').eq('safety_status', 'SAFE').is('target_user_id', null).in('classification_status', ['CLASSIFIED', 'UNCLASSIFIED']))"), 'Only public, OPEN, safe, untargeted and publishable Requests belong in discovery');
assert(repo.includes('TTL_MS = 30000') && repo.includes('.dedupe('), 'Bounded shared cache and in-flight dedupe');
assert(repo.includes('.range('), 'No silent truncation at Supabase row limit');
assert(repo.includes('fetchTaxonomyFromDB({ strict: true })'), 'Shared real taxonomy with explicit errors');
assert(!ui.includes('.from('), 'UI delegates database ownership');
assert(ui.includes('repo.loadRequests(') && ui.includes('repo.load('), 'Two distinct data sources');
assert(ui.includes("window.LYANN_ROUTER.go('messages'"), 'Use canonical messaging route');
assert(ui.includes('window.openPublicMemberProfile') && ui.includes('window.openLyannDetailModal'), 'Reuse canonical detail surfaces');
for (const state of ['LOADING','SUCCESS','EMPTY','ERROR']) assert(ui.includes(`'${state}'`), `${state} is explicit`);
for (const file of ['session-store.js','auth-state.js','data-cache.js','explorer-repository.js','explorer-ui.js']) assert(results.includes(file), `${file} loaded`);
assert.equal((api.match(/async getUserServices\(/g)||[]).length,1,'One service API contract');
console.log('Explorer dual-discovery architecture audit passed.');
